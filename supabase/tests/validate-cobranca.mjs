import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {criarBancoLocal} from './banco-local.mjs';
let db, n=0;
const owner=randomUUID(), outsider=randomUUID(), manager=randomUUID();
const scalar=async s=>Object.values((await db.query(s)).rows[0])[0];
const login=async id=>db.exec(`reset role;select set_config('request.jwt.claim.sub','${id}',false);set role authenticated`);
const ok=(value,label)=>{assert.ok(value,label);console.log('PASS',label);n++;};
const fail=async(sql,code,label)=>{await assert.rejects(()=>db.exec(sql),e=>e.code===code);console.log('PASS',label);n++;};
try {
  db=await criarBancoLocal('20261001000600');
  await db.exec(`insert into auth.users values('${owner}'),('${outsider}'),('${manager}')`);
  await login(owner);
  const office=await scalar("select public.criar_oficina('Homologação cobrança',null)");
  const sql=(acao,plano='complete',chave=randomUUID())=>`select public.simular_cobranca('${office}','${chave}','${acao}','${plano}')`;
  ok(!(await scalar(`select public.consultar_cobranca_teste('${office}')`)).habilitado,'Simulação desabilitada por padrão');
  await fail(sql('aprovar'),'42501','Dono não habilita simulador sozinho');
  await fail(`insert into public.oficinas_cobranca_teste(oficina_id,habilitado) values('${office}',true)`,'42501','Configuração não aceita escrita direta');
  await db.exec(`reset role;insert into public.oficinas_cobranca_teste(oficina_id,habilitado) values('${office}',true);insert into public.membros_oficina(oficina_id,usuario_id,perfil) values('${office}','${manager}','manager')`);
  await login(outsider);
  await fail(sql('aprovar'),'42501','Outra conta não altera assinatura');
  await login(manager);
  await fail(sql('aprovar'),'42501','Gerente não altera assinatura');
  await login(owner);
  await fail(sql('aprovar','inventado'),'22023','Plano inválido rejeitado');
  const key=randomUUID(), evento=await scalar(sql('aprovar','complete',key));
  ok(evento===await scalar(sql('aprovar','complete',key)),'Retry idempotente não cria segunda cobrança');
  await fail(sql('cancelar','complete',key),'22023','Mesma chave com outro cenário rejeitada');
  let acesso=(await scalar('select public.consultar_meu_acesso()'))[0];
  ok(acesso.codigo_plano==='complete'&&acesso.recursos.includes('ai'),'Aprovação libera recursos reais do plano');
  let cobranca=await scalar(`select public.consultar_cobranca_teste('${office}')`);
  ok(cobranca.eventos.length===1&&cobranca.eventos[0].valor_centavos===19900,'Preço calculado no servidor e histórico único');
  await scalar(sql('recusar','basic'));
  acesso=(await scalar('select public.consultar_meu_acesso()'))[0];
  ok(acesso.codigo_plano==='complete'&&acesso.situacao==='active','Recusa preserva assinatura anterior');
  await scalar(sql('atrasar'));
  acesso=(await scalar('select public.consultar_meu_acesso()'))[0];
  ok(acesso.situacao==='past_due'&&acesso.recursos.length===0,'Atraso bloqueia acesso no servidor');
  await scalar(sql('aprovar','basic'));
  acesso=(await scalar('select public.consultar_meu_acesso()'))[0];
  ok(acesso.recursos.includes('customers')&&!acesso.recursos.includes('ai'),'Nova aprovação restaura somente recursos contratados');
  await scalar(sql('cancelar','basic'));
  acesso=(await scalar('select public.consultar_meu_acesso()'))[0];
  ok(acesso.situacao==='cancelled'&&acesso.recursos.length===0,'Cancelamento bloqueia módulos');
  ok((await scalar(`select public.consultar_cobranca_teste('${office}')`)).eventos.length===5,'Dono consulta histórico mesmo com plano bloqueado');
  await fail(`update public.eventos_cobranca_teste set valor_centavos=1`,'42501','Histórico não aceita alteração direta');
  await db.exec(`reset role;update public.assinaturas_oficina set provedor_cobranca='provedor-real' where oficina_id='${office}'`);
  await login(owner);
  await fail(sql('aprovar'),'42501','Simulador não altera assinatura de provedor real');
  console.log(`${n} verificações aprovadas.`);
} catch(e) {console.error('FAIL',e.message,e.code||'');process.exitCode=1;} finally {if(db) await db.close();}

  ok((await ler(o.id)).itens.length===3,'Recusa financeira não remove itens parcialmente');
  o=await save(o,{...payload(o),itens:o.itens.map(i=>({...i,situacao:'done'}))});
  await db.exec(`reset role;update public.ordens_servico set situacao='ready' where id='${o.id}'`);await login(owner);o=await ler(o.id);
  const ready=payload(o);ready.itens.push(item({descricao:'Conferência adicional'}));o=await save(o,ready);
  ok(o.situacao==='in_progress','Alterar itens de OS pronta devolve à execução');
  const semPeca=payload(o);semPeca.itens=semPeca.itens.filter(i=>i.tipo!=='part').map(i=>({...i,situacao:'done'}));o=await save(o,semPeca);
  await db.exec(`reset role;update public.ordens_servico set situacao='ready' where id='${o.id}';update public.ordens_servico set situacao='delivered',entregue_em=now() where id='${o.id}'`);
  ok(Number(await scalar('select saldo from public.estoque_produtos where item_catalogo_id=$1',[part]))===10,'Peça removida não gera baixa de estoque na entrega');
  await login(owner);o=await ler(o.id);
  await fail(()=>save(o,payload(o)),'22023','OS entregue continua protegida');

  const q=await scalar('select public.salvar_orcamento($1,$2,$3)',[w,{cliente_id:c,veiculo_id:v,itens:[{descricao:'Original',tipo:'service',unidade:'serv',quantidade:1,preco_unitario_centavos:7000}],desconto_centavos:0},randomUUID()]);
  const pendente=await scalar('select public.criar_os_aguardando_orcamento($1,$2)',[w,q.id]);
  let vinculada=await ler(typeof pendente==='string'?pendente:pendente.id);
  await fail(()=>save(vinculada,{...payload(vinculada),itens:[item()]}),'22023','Orçamento pendente precisa ser autorizado antes de editar serviços');
  await scalar('select public.autorizar_servico_pela_os($1,$2,$3,$4,$5,$6)',[w,vinculada.id,vinculada.revisao,q.id,q.revisao,q.versao.id]);
  vinculada=await ler(vinculada.id);
  vinculada=await save(vinculada,{...payload(vinculada),itens:[...vinculada.itens,item({descricao:'Extra realizado'})]});
  ok(vinculada.total_centavos===12000,'OS originada de orçamento também aceita serviço adicional');
  const itemOriginal=vinculada.itens[0];
  vinculada=await save(vinculada,{...payload(vinculada),itens:vinculada.itens.filter(i=>i.id!==itemOriginal.id)});

// Traduz identificadores SQL sem modificar valores literais, códigos ou documentos JSON existentes.
// Os corpos das funções são processados separadamente do delimitador $$.
export function traduzirSql(sql, mapa = {...tabelas,...colunas,...operacoes}, literais = {}) {
  return sql.replace(/--[^\n]*|\/\*[\s\S]*?\*\/|'(?:''|[^'])*'|"(?:""|[^"])*"|\b[A-Za-z_][A-Za-z_0-9]*\b/g, token => {
    if (token.startsWith('--') || token.startsWith('/*')) return token
    if (token.startsWith("'")) {
      const valor = token.slice(1,-1).replaceAll("''", "'")
      return Object.hasOwn(literais,valor) ? "'" + literais[valor].replaceAll("'","''") + "'" : token
    }
    if (token.startsWith('"')) return token
    return mapa[token] ?? token
  })
}
